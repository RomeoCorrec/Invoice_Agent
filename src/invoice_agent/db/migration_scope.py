"""Which database objects Alembic is responsible for.

LangGraph creates and migrates its own checkpoint tables (``checkpoints``, ``checkpoint_blobs``,
``checkpoint_writes``, ``checkpoint_migrations``). They are not on our models, so without this
filter an autogenerated migration would propose to drop them. The ledger's schema is handled
the same way: it has its own table definitions.
"""

from typing import Any

LANGGRAPH_TABLE_PREFIX = "checkpoint"


def include_object(
    obj: Any, name: str | None, type_: str, reflected: bool, compare_to: Any
) -> bool:
    if type_ == "table" and reflected and compare_to is None and name is not None:
        return not name.startswith(LANGGRAPH_TABLE_PREFIX)
    return True
